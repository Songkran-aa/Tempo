// Generates the Tempo logo: web/assets/logo-mark.svg (rounded app icon) + logo-square.svg (full-bleed, for maskable/iOS).
// Run from the project folder:  node scripts/logo/logo-build.mjs   (PNG exports: see scripts/logo/logo-render.html)
//
// Concept — rhythm bars. Four beats of different weight (the work, rising to a peak and settling),
// then the coral dot: the next beat, the launch, always just ahead.
// 3 colours only: Indigo (app accent) · Coral · White.
import { writeFileSync } from "node:fs";

const INDIGO = "#4F46E5", CORAL = "#FF6B4A", WHITE = "#FFFFFF";
const W = 48, STEP = 72, CY = 256;                 // bar width, bar spacing, vertical centre
const heights = [64, 168, 288, 128];               // beat heights (incl. round caps)
const DOT = 28;                                    // coral dot radius; it sits in the 5th slot
const x0 = 256 - (heights.length * STEP + W / 2 + DOT) / 2;   // centre bars + dot horizontally

const art = [
  ...heights.map((h, i) => `<rect x="${x0 + i * STEP}" y="${CY - h / 2}" width="${W}" height="${h}" rx="${W / 2}" fill="${WHITE}"/>`),
  `<circle cx="${x0 + heights.length * STEP + W / 2}" cy="${CY}" r="${DOT}" fill="${CORAL}"/>`,
].join("\n  ");

const svg = rx => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-label="Tempo">
  <!-- Tempo — 3 colours: Indigo ${INDIGO} · Coral ${CORAL} · White ${WHITE}
       Rhythm bars; the coral dot is the next beat. Generated by scripts/logo/logo-build.mjs -->
  <rect width="512" height="512" rx="${rx}" fill="${INDIGO}"/>
  ${art}
</svg>
`;
writeFileSync("web/assets/logo-mark.svg", svg(118));
writeFileSync("web/assets/logo-square.svg", svg(0));
console.log("ok");
